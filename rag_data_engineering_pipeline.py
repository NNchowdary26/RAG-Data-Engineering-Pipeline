# Generate Embeddings
def generate_embeddings(chunks):

    texts = [
        chunk["text"]
        for chunk in chunks
    ]

    embeddings = embedding_model.encode(
        texts,
        batch_size=32,
        show_progress_bar=True,
        normalize_embeddings=True
    )

    return np.array(
        embeddings,
        dtype="float32"
    )

# FAISS Index
def create_faiss_index(embeddings):

    dimension = embeddings.shape[1]

    index = faiss.IndexFlatIP(
        dimension
    )

    index.add(embeddings)

    return index

# Vector Database
INDEX_FILE = VECTOR_DIR / "faiss.index"

METADATA_FILE = VECTOR_DIR / "chunks.pkl"

def save_vector_store(index, chunks):

    faiss.write_index(
        index,
        str(INDEX_FILE)
    )

    with open(METADATA_FILE, "wb") as f:

        pickle.dump(
            chunks,
            f
        )

    print("Vector store saved.")

def load_vector_store():

    index = faiss.read_index(
        str(INDEX_FILE)
    )

    with open(METADATA_FILE, "rb") as f:

        chunks = pickle.load(f)

    return index, chunks

# Complete Pipeline
def run_pipeline():

    catalog = load_catalog()

    all_new_chunks = []

    statistics = {

        "total_files": 0,
        "new_files": 0,
        "modified_files": 0,
        "unchanged_files": 0,
        "failed_files": 0,
        "total_chunks": 0

    }

    for file_path in RAW_DIR.iterdir():

        if file_path.suffix.lower() not in [
            ".pdf",
            ".txt",
            ".md"
        ]:
            continue

        statistics["total_files"] += 1

        status, file_hash = determine_document_status(
            file_path,
            catalog
        )

        print(
            f"{file_path.name}: {status}"
        )

        if status == "UNCHANGED":

            statistics["unchanged_files"] += 1
            continue

        try:

            document = ingest_document(
                file_path
            )

            validation = validate_document(
                document
            )

            if not validation["valid"]:

                print(
                    "Validation failed:",
                    validation["errors"]
                )

                statistics["failed_files"] += 1
                continue

            document = clean_document(
                document
            )

            chunks = create_chunks(
                document
            )

            all_new_chunks.extend(
                chunks
            )

            catalog[file_path.name] = {

                "document_id":
                    document["document_id"],

                "file_hash":
                    file_hash,

                "file_type":
                    document["file_type"],

                "chunk_count":
                    len(chunks),

                "last_processed":
                    datetime.utcnow().isoformat()

            }

            if status == "NEW":
                statistics["new_files"] += 1

            elif status == "MODIFIED":
                statistics["modified_files"] += 1

            statistics["total_chunks"] += len(chunks)

        except Exception as e:

            print(
                f"ERROR processing {file_path.name}: {e}"
            )

            statistics["failed_files"] += 1

    save_catalog(catalog)

    print("\nPIPELINE SUMMARY")
    print("=" * 40)

    for key, value in statistics.items():

        print(
            f"{key}: {value}"
        )

    return all_new_chunks

