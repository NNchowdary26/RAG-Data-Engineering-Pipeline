# Detect new and modified documents
def determine_document_status(file_path, catalog):

    file_hash = calculate_file_hash(file_path)

    filename = file_path.name

    if filename not in catalog:

        return "NEW", file_hash

    previous_hash = catalog[filename]["file_hash"]

    if previous_hash != file_hash:

        return "MODIFIED", file_hash

    return "UNCHANGED", file_hash

# Document Chunking
def chunk_text(
    text,
    chunk_size=800,
    overlap=150
):

    words = text.split()

    chunks = []

    start = 0

    while start < len(words):

        end = start + chunk_size

        chunk = " ".join(
            words[start:end]
        )

        if chunk.strip():

            chunks.append(chunk)

        start += chunk_size - overlap

    return chunks

# Create structured chunks
def create_chunks(document):

    chunks = []

    chunk_counter = 0

    for page in document["pages"]:

        text = page["text"]

        page_chunks = chunk_text(text)

        for chunk in page_chunks:

            chunk_id = (
                f"{document['document_id']}_"
                f"{chunk_counter}"
            )

            chunks.append({

                "chunk_id": chunk_id,

                "document_id":
                    document["document_id"],

                "file_name":
                    document["file_name"],

                "page_number":
                    page["page_number"],

                "chunk_index":
                    chunk_counter,

                "text":
                    chunk,

                "created_at":
                    datetime.utcnow().isoformat()

            })

            chunk_counter += 1

    return chunks

